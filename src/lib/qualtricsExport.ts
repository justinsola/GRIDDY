					oLabel.style.padding = "0 2px 1px";
					oLabel.style.color = "#2a241c";
					oLabel.style.backgroundColor = hexToRgba(respColor, 0.3);
					oLabel.style.borderTop = "1px solid " + hexToRgba(respColor, 0.4);
